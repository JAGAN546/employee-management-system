const ADMIN_HR_MANAGER_LINKS = [
  { to: '/dashboard', label: 'Dashboard', icon: 'dashboard' },
  { to: '/employees', label: 'Employees', icon: 'employees' },
  { to: '/notifications', label: 'Notifications', icon: 'notifications' },
];

const PAGE_TITLES = {
  '/dashboard': 'Dashboard',
  '/employees': 'Employees',
  '/attendance': 'Attendance',
  '/leaves': 'Leave Management',
  '/tasks': 'My Tasks',
  '/notifications': 'Notifications',
  '/profile': 'My Profile',
};

/**
 * App shell component (kept named Navbar so existing imports still work).
 * Renders Sidebar + TopBar + the page content (children).
 */
const Navbar = ({ children }) => {
  const { user, logoutUser } = useAuth();
  const navigate = useNavigate();
  const location = useLocation();
  const [sidebarOpen, setSidebarOpen] = useState(false);

  const handleLogout = () => {
    logoutUser();
    navigate('/login');
  };

  const links = user?.role === 'EMPLOYEE' ? EMPLOYEE_LINKS : ADMIN_HR_MANAGER_LINKS;
  const pageTitle = PAGE_TITLES[location.pathname] || 'EMS';

  const closeSidebar = () => setSidebarOpen(false);

  return (
    <div className="app-layout">
      {/* Mobile overlay */}
      <div
        className={`sidebar-overlay ${sidebarOpen ? 'open' : ''}`}
        onClick={closeSidebar}
      />

      {/* Sidebar */}
      <aside className={`sidebar ${sidebarOpen ? 'open' : ''}`}>
        <div className="sidebar-header">
          <span className="sidebar-logo">EMS</span>
        </div>

        <nav className="sidebar-nav">
          {links.map((link) => (
            <Link
              key={link.to}
              to={link.to}
              className={`nav-link ${location.pathname === link.to ? 'active' : ''}`}
              onClick={closeSidebar}
            >
              {icons[link.icon]}
              {link.label}
            </Link>
          ))}
        </nav>
      </aside>

      {/* Main area: TopBar + Page Content */}
      <div className="main-wrapper">
        <header className="topbar">
          <div className="flex gap-3" style={{ alignItems: 'center' }}>
            <button
              className="mobile-menu-btn"
              onClick={() => setSidebarOpen(true)}
              aria-label="Open menu"
            >
              {icons.menu}
            </button>
            <h1 className="topbar-title">{pageTitle}</h1>
          </div>

          <div className="topbar-right">
            <div className="user-info">
              <span className="user-email">{user?.email}</span>
              <span className="user-role">{user?.role}</span>
            </div>
            <button className="btn btn-secondary btn-sm" onClick={handleLogout}>
              Logout
            </button>
          </div>
        </header>

        <main className="page-content">
          {children}
        </main>
      </div>
    </div>
  );
};

export default Navbar;